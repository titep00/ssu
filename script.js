function updateAddPreview() {
  const name = els.addName.value.trim() || "세팅 이름";
  if (name) els.addName.classList.remove("field-error");
  const emoji = els.addEmoji.value.trim() || "🎬";
  const tag = els.addTag.value.trim() || "태그";
  const desc = els.addDesc.value.trim();
  const temp = { name, tag, desc, keywords: name + " " + tag + " " + desc };
  const recCount = Math.max(allProps(temp).length, MIN_PROPS);
  const infoCount = allInfo(temp).length;
  const tipsCount = allTips(temp).length;
  const text = (name + " " + tag + " " + desc).toLowerCase();
  const recs = PROP_LIBRARY
    .filter((p) => p.themes.some((t) => t !== "공통" && text.includes(t)))
    .slice(0, 6)
    .map((p) => `${p.name} · ${p.priority}`);
  els.addPreviewEmoji.textContent = emoji;
  els.addPreview.innerHTML = `
    <div class="card-thumb" style="background:linear-gradient(135deg, ${DEFAULT_COLORS.join(", ")})">
      <span>${escAttr(emoji)}</span>
      <span class="card-tag">${escAttr(tag)}</span>
    </div>
    <div class="card-body">
      <h3>${escAttr(name)}</h3>
      <p>${escAttr(desc) || "한 줄 설명 입력 중…"}</p>
      <div class="card-meta">
        <span>정보 ${infoCount}건 · 팁 ${tipsCount}건 · 소품 ${recCount}종</span>
        <span>실시간 미리보기</span>
      </div>
    </div>`;
  const autoBox = els.addPreview.nextElementSibling;
  autoBox.innerHTML = recs.length
    ? `<span class="auto-rec-label">자동 추천 소품</span>${recs.map((r) => `<span class="auto-rec-chip">${escAttr(r)}</span>`).join("")}`
    : '<span class="auto-rec-note">이름·설명을 입력하면 소품이 자동 추천됩니다.</span>';
}

