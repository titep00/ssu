const CUSTOM_SETTINGS_KEY = "setwithCustomSettings";
const DEFAULT_COLORS = ["#33516b", "#6b8fad", "#d9a05b", "#8a6f4d", "#5d4a36"];

function loadCustomSettings() {
  try {
    const saved = JSON.parse(localStorage.getItem(CUSTOM_SETTINGS_KEY) || "[]");
    if (saved.length) settings = [...saved, ...settings.filter((s) => !s.custom)];
  } catch (e) {
    localStorage.removeItem(CUSTOM_SETTINGS_KEY);
  }
}

function persistCustomSettings() {
  localStorage.setItem(CUSTOM_SETTINGS_KEY, JSON.stringify(settings.filter((s) => s.custom)));
}

function parsePriority(raw) {
  const v = (raw || "").trim();
  if (v.includes("필수")) return "필수";
  if (v.includes("선택")) return "선택";
  return "추천";
}

function parsePropLines(text) {
  return (text || "")
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean)
    .map((line) => {
      const parts = line.split("|").map((s) => s.trim());
      return {
        name: parts[0],
        priority: parsePriority(parts[1]),
        desc: parts[2] || "",
      };
    });
}

function buildCustomSetting() {
  const name = els.addName.value.trim();
  const emoji = els.addEmoji.value.trim() || "🎬";
  const tag = els.addTag.value.trim() || "직접 추가";
  const desc = els.addDesc.value.trim() || "";
  const props = parsePropLines(els.addProps.value);
  const info = els.addInfo.value.split("\n").map((s) => s.trim()).filter(Boolean);
  const tips = els.addTips.value.split("\n").map((s) => s.trim()).filter(Boolean);
  return {
    id: "custom-" + Date.now(),
    custom: true,
    name,
    emoji,
    tag,
    desc,
    keywords: name + " " + tag + " " + desc + " " + props.map((p) => p.name).join(" "),
    colors: DEFAULT_COLORS.slice(),
    info: info.length ? info : ["직접 입력한 세팅 시나리오입니다."],
    tips: tips.length ? tips : ["세팅 팁이 입력되지 않았어요."],
    props,
  };
}

