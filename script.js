function allProps(setting) {
  const core = (setting.props || []).map((p) => ({ ...p }));
  if (core.length >= MIN_PROPS) return core;
  const text = ((setting.name || "") + " " + (setting.tag || "") + " " + (setting.desc || "") + " " + (setting.keywords || "")).toLowerCase();
  const existing = new Set(core.map((p) => p.name));
  const matches = [];
  for (const p of PROP_LIBRARY) {
    if (existing.has(p.name)) continue;
    const score = p.themes.includes("공통")
      ? 1
      : p.themes.reduce((a, t) => a + (text.includes(t) ? 1 : 0), 0);
    if (score > 0) matches.push({ p, score });
  }
  matches.sort((a, b) => b.score - a.score);
  for (const { p } of matches) {
    if (core.length >= MIN_PROPS) break;
    existing.add(p.name);
    core.push({ ...p });
  }
  return core;
}

function allInfo(setting) {
  const core = (setting.info || []).slice();
  if (core.length >= MIN_INFO) return core;
  const text = ((setting.name || "") + " " + (setting.tag || "") + " " + (setting.desc || "") + " " + (setting.keywords || "")).toLowerCase();
  const existing = new Set(core);
  const matches = [];
  for (const item of INFO_LIBRARY) {
    if (existing.has(item.text)) continue;
    const score = item.themes.includes("공통") ? 1 : item.themes.reduce((a, t) => a + (text.includes(t) ? 1 : 0), 0);
    if (score > 0) matches.push({ item, score });
  }
  matches.sort((a, b) => b.score - a.score);
  for (const { item } of matches) {
    if (core.length >= MIN_INFO) break;
    existing.add(item.text);
    core.push(item.text);
  }
  return core;
}

function allTips(setting) {
  const core = (setting.tips || []).slice();
  if (core.length >= MIN_TIPS) return core;
  const text = ((setting.name || "") + " " + (setting.tag || "") + " " + (setting.desc || "") + " " + (setting.keywords || "")).toLowerCase();
  const existing = new Set(core);
  const matches = [];
  for (const item of TIPS_LIBRARY) {
    if (existing.has(item.text)) continue;
    const score = item.themes.includes("공통") ? 1 : item.themes.reduce((a, t) => a + (text.includes(t) ? 1 : 0), 0);
    if (score > 0) matches.push({ item, score });
  }
  matches.sort((a, b) => b.score - a.score);
  for (const { item } of matches) {
    if (core.length >= MIN_TIPS) break;
    existing.add(item.text);
    core.push(item.text);
  }
  return core;
}

