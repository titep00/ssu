function printChecklist() {
  const lines = checklist.map((c, i) => {
    const lbl = settingLabel(c);
    return `${i + 1}. [${lbl.name}] ${c.prop}${c.platform && c.price ? ` — ${c.platform} ${formatPrice(c.price)}` : ""}${c.done ? " (완료)" : ""}`;
  }).join("\n");
  const w = window.open("", "_blank");
  w.document.write(`<pre style="font-family:Malgun Gothic;font-size:14px">세트위드 소품 체크리스트\n${"=".repeat(30)}\n\n${lines || "없음"}</pre>`);
  w.document.close();
  w.print();
}

function downloadSpreadsheet() {
  if (!checklist.length) {
    alert("체크리스트가 비어 있어요. 세팅 가이드에서 소품을 담아보세요.");
    return;
  }
  const header = ["번호", "세팅", "소품", "최저가 플랫폼", "최저가(원)", "구매 링크", "상태"];
  const rows = checklist.map((c, i) => {
    const lbl = settingLabel(c);
    return [i + 1, lbl.name, c.prop, c.platform || "", c.price || "", c.link || "", c.done ? "완료" : "미완료"];
  });
  const esc = (v) => `"${String(v).replace(/"/g, '""')}"`;
  const csv = "\uFEFF" + [header, ...rows].map((r) => r.map(esc).join(",")).join("\r\n");
  const blob = new Blob([csv], { type: "text/csv;charset=utf-8;" });
  const a = document.createElement("a");
  a.href = URL.createObjectURL(blob);
  a.download = "세트위드_소품_체크리스트.csv";
  document.body.appendChild(a);
  a.click();
  setTimeout(() => { URL.revokeObjectURL(a.href); a.remove(); }, 0);
}

